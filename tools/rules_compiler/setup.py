#!/usr/bin/env python3
"""Compile audited immutable setup facts into C++ tables; no replay inputs."""
import argparse
import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GAME_SHA = '0861bfa1df347538d932f22d580e75420f08082792eb914e53b4882764acdbe9'


def compile_tables(source):
    raw = source.read_bytes()
    data = json.loads(raw)
    if data['reference']['game_dll_sha256'] != GAME_SHA:
        raise ValueError('Definitions target another build')
    names = set(['CARD.ASCENDERS_BANE'])
    tags = set()
    def add(value):
        if isinstance(value, str) and value.startswith(('ACT.', 'EVENT.', 'ENCOUNTER.', 'RELIC.', 'CARD.', 'CARD_POOL.', 'POTION.', 'CHARACTER.')):
            names.add(value)
        elif isinstance(value, list):
            for item in value:
                add(item)
        elif isinstance(value, dict):
            for key, item in value.items():
                if key == 'tags':
                    tags.update(item)
                else:
                    add(item)
    for key in ('acts', 'characters', 'shared_events', 'shared_ancients', 'shared_relics', 'neow_positive', 'neow_curses', 'neow_all', 'native_defaults', 'shared_potions'):
        add(data[key])
    names = sorted(names)
    ids = {name: index for index, name in enumerate(names)}
    tagbits = {tag: 1 << index for index, tag in enumerate(sorted(tags))}
    if len(ids) >= 65535 or len(tagbits) > 64:
        raise ValueError('Definition IDs/tags exceed storage')
    native_defaults = json.dumps(data['native_defaults'], separators=(',', ':'), sort_keys=True)
    lines = ['// Generated by tools/rules_compiler/setup.py; do not edit.',
             '// Audited immutable definitions SHA-256: ' + hashlib.sha256(raw).hexdigest(),
             '#include "sts2/rules/setup.hpp"', '', 'namespace sts2::engine { namespace {',
             'constexpr std::array<std::string_view, ' + str(len(names)) + '> content_names = {',
             ',\n'.join(json.dumps(name) for name in names), '};',
             'constexpr std::string_view native_defaults_table = ' + json.dumps(native_defaults) + ';']
    def content_array(symbol, values):
        lines.append(f'constexpr std::array<ContentId, {len(values)}> {symbol} = {{' + ','.join(str(ids[v]) for v in values) + '};')
    def relic_array(symbol, values):
        supported = {'Common':'common', 'Uncommon':'uncommon', 'Rare':'rare', 'Shop':'shop', 'Event':'event', 'Ancient':'ancient', 'Starter':'starter'}
        rows = [f'RelicEntry{{{ids[v["id"]]}, RelicTier::{supported.get(v["rarity"], "other")}}}' for v in values]
        lines.append(f'constexpr std::array<RelicEntry, {len(rows)}> {symbol} = {{' + ','.join(rows) + '};')
    def encounters(symbol, values):
        rows = [f'EncounterEntry{{{ids[v["id"]]}, UINT64_C({sum(tagbits[t] for t in v["tags"])})}}' for v in values]
        lines.append(f'constexpr std::array<EncounterEntry, {len(rows)}> {symbol} = {{' + ','.join(rows) + '};')
    content_array('neow_positive_table', data['neow_positive'])
    content_array('neow_curses_table', data['neow_curses'])
    relic_array('shared_relic_table', data['shared_relics'])
    content_array('shared_event_table', data['shared_events'])
    content_array('shared_ancient_table', data['shared_ancients'])
    def card_array(symbol, values):
        rows = [f'CardEntry{{{ids[v["id"]]}, ContentRarity::{v["rarity"].lower() if v["rarity"] in ("Common", "Uncommon", "Rare") else "other"}, {str(v["upgradable"]).lower()}}}' for v in values]
        lines.append(f'constexpr std::array<CardEntry, {len(rows)}> {symbol} = {{' + ','.join(rows) + '};')
    def potion_array(symbol, values):
        rows = [f'PotionEntry{{{ids[v["id"]]}, ContentRarity::{v["rarity"].lower() if v["rarity"] in ("Common", "Uncommon", "Rare") else "other"}}}' for v in values]
        lines.append(f'constexpr std::array<PotionEntry, {len(rows)}> {symbol} = {{' + ','.join(rows) + '};')
    potion_array('shared_potion_table', data['shared_potions'])
    acts = []
    for index, act in enumerate(data['acts']):
        symbol = f'act_{index}'
        for key in ('events', 'ancients'):
            content_array(symbol + '_' + key, act[key])
        for key in ('weak', 'normal', 'elite', 'bosses'):
            encounters(symbol + '_' + key, act[key])
        acts.append('ActDefinition{' + ','.join([str(ids[act['id']]), str(act['index']), str(act['rooms']), str(act['weak_count']), str(act['is_default']).lower(), *[symbol+'_'+k for k in ('events','ancients','weak','normal','elite','bosses')]]) + '}')
    lines.append(f'constexpr std::array<ActDefinition, {len(acts)}> act_table = {{' + ','.join(acts) + '};')
    characters = []
    for index, char in enumerate(data['characters']):
        symbol = f'character_{index}'
        content_array(symbol+'_deck', char['deck'])
        content_array(symbol+'_relics', char['relics'])
        relic_array(symbol+'_pool', char['relic_pool'])
        card_array(symbol+'_cards', char['card_pool'])
        potion_array(symbol+'_potions', char['potion_pool'])
        characters.append('CharacterDefinition{' + ','.join([str(ids[char['id']]), str(char['hp']), str(char['gold']), str(char['orb_slots']), str(char['energy']), symbol+'_deck', symbol+'_relics', symbol+'_pool', str(ids[char['card_pool_id']]), symbol+'_cards', symbol+'_potions']) + '}')
    lines += [f'constexpr std::array<CharacterDefinition, {len(characters)}> character_table = {{' + ','.join(characters) + '};',
        '}',
        'std::string_view SetupRules::fingerprint() noexcept { return "' + hashlib.sha256(raw).hexdigest() + '"; }',
        'std::string_view SetupRules::native_defaults() noexcept { return native_defaults_table; }',
        'std::span<const ContentId> SetupRules::neow_positive() noexcept { return neow_positive_table; }',
        'std::span<const ContentId> SetupRules::neow_curses() noexcept { return neow_curses_table; }',
        'std::span<const ActDefinition> SetupRules::acts() noexcept { return act_table; }',
        'std::span<const CharacterDefinition> SetupRules::characters() noexcept { return character_table; }',
        'std::span<const PotionEntry> SetupRules::shared_potions() noexcept { return shared_potion_table; }',
        'std::span<const RelicEntry> SetupRules::shared_relics() noexcept { return shared_relic_table; }',
        'std::span<const ContentId> SetupRules::shared_events() noexcept { return shared_event_table; }',
        'std::span<const ContentId> SetupRules::shared_ancients() noexcept { return shared_ancient_table; }',
        'std::string_view SetupRules::name(ContentId id) noexcept { return id < content_names.size() ? content_names[id] : std::string_view{}; }',
        'ContentId SetupRules::find(std::string_view name) noexcept { for (ContentId i = 0; i < content_names.size(); ++i) if (content_names[i] == name) return i; return no_content; }',
        'const ActDefinition* SetupRules::act(ContentId id) noexcept { for (const auto& act : act_table) if (act.id == id) return &act; return nullptr; }',
        'const CharacterDefinition* SetupRules::character(ContentId id) noexcept { for (const auto& character : character_table) if (character.id == id) return &character; return nullptr; }',
        '} // namespace sts2::engine', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=REPO / 'data/builds/v0.111.0/setup.json')
    parser.add_argument('--output', type=Path, default=REPO / 'src/rules/setup.g.cpp')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = compile_tables(args.input)
    if args.check:
        if args.output.read_text() != result:
            raise ValueError('Generated setup definitions differ; recompile audited tables')
    else:
        args.output.write_text(result)


if __name__ == '__main__':
    main()

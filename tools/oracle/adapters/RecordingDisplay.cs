// Presentation only. Gameplay transitions and rewards are driven by recorded actions.
using System.Text.Json;
using MegaCrit.Sts2.Core.Combat;
using MegaCrit.Sts2.Core.Models;
using MegaCrit.Sts2.Core.Rooms;
using MegaCrit.Sts2.Core.Runs;

namespace Sts2Headless;
public partial class RunSimulator {
    private Dictionary<string, object?> DisplayCard(CardModel card, int index) => new() {
        ["index"] = index, ["id"] = card.Id.ToString(), ["name"] = _loc.Card(card.Id.Entry),
        ["cost"] = card.EnergyCost.GetResolved(), ["type"] = card.Type.ToString(),
        ["rarity"] = card.Rarity.ToString(), ["upgraded"] = card.IsUpgraded,
        ["description"] = _loc.Bilingual("cards", card.Id.Entry + ".description"),
        ["stats"] = card.DynamicVars.Values.ToDictionary(v => v.Name.ToLowerInvariant(), v => (object)v.BaseValue),
        ["keywords"] = card.Keywords.Select(k => k.ToString()).ToArray(),
        ["after_upgrade"] = GetUpgradedInfo(card)
    };

    public Dictionary<string, object?> OracleDisplay(JsonElement command) {
        Require(_oracleRunMode, "The interface requires the run recording backend");
        if (command.TryGetProperty("lang", out var lang)) _loc.Lang = lang.GetString() ?? "en";
        var player = _runState!.Players.Single();
        if (_oracleRunEndingReason != null) return GameOverState(_oracleRunEndingReason == "victory");
        Dictionary<string, object?> Choice(string kind) => new() {
            ["type"] = "decision", ["decision"] = kind, ["context"] = RunContext(),
            ["player"] = PlayerSummary(player)
        };
        if (_pendingBundles != null) {
            var result = Choice("bundle_select");
            result["bundles"] = _pendingBundles.Select((cards, i) => new {
                index = i, cards = cards.Select(DisplayCard).ToArray() }).ToArray();
            return result;
        }
        if (_runSelector.Pending is { } pending) {
            var result = Choice(pending.Kind);
            result["cards"] = pending.Cards.Select(DisplayCard).ToArray();
            if (pending.Kind == "card_select") {
                result["min_select"] = pending.Prefs.MinSelect;
                result["cancelable"] = pending.Prefs.Cancelable;
                result["max_select"] = Math.Min(pending.Prefs.MaxSelect, pending.Cards.Count);
            } else result["can_skip"] = pending.Alternatives.Any(a => a.GetType().Name.Contains("Skip"));
            return result;
        }
        Require(RewardFrames().Length == 0, "Resolve rewards through recorded actions before display");
        var room = _runState.CurrentRoom;
        if (room is CombatRoom && CombatManager.Instance.IsInProgress) return CombatPlayState(player);
        if (room is EventRoom eventRoom) return RecordingEventState(eventRoom);
        if (room is MerchantRoom shop) return ShopState(shop, player);
        if (room is RestSiteRoom rest && rest.Options.Any(o => o.IsEnabled)) return RestSiteState(rest);
        if (room is MapRoom || room == null) {
            Require(_runState.Map != null, "Map must be generated by gameplay before display");
            return MapSelectState();
        }
        throw new InvalidOperationException("Gameplay must settle before requesting display");
    }
}
